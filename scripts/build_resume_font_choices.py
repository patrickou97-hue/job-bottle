#!/usr/bin/env python3
"""Build the resume fonts from upstream TrueType binaries.

Inputs: Google Fonts Noto Sans SC variable TTF, Liberation 2.1.5 TTFs,
Zhuque Fangsong 0.212 Regular, and Google Fonts Carlito Regular/Bold.
The original licenses ship beside the generated assets.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

from build_resume_font_subset import FONT_DIR, ROOT, build_charset, codepoint_ranges, subset_font


def coverage(paths: list[Path]) -> set[int]:
    maps = []
    for path in paths:
        with TTFont(path) as font:
            maps.append(set(font.getBestCmap()))
    return set.intersection(*maps)


def sample(source: Path, destination: Path, text: str) -> None:
    options = subset.Options()
    options.flavor = "woff"
    options.recalc_timestamp = False
    font = subset.load_font(str(source), options)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    subset.save_font(font, str(destination), options)


def alternate_cjk(
    source: Path,
    destination: Path,
    family: str,
    weight: str,
    charset: set[int],
) -> None:
    subset_font(source, destination, charset)
    # Subsetting changes the font. Do not retain the upstream reserved names
    # as the primary internal family or font names in the modified files.
    with TTFont(destination, recalcTimestamp=False) as font:
        names = {
            1: family, 2: weight, 3: f"{family} {weight} v1",
            4: f"{family} {weight}", 6: f"{family.replace(' ', '')}-{weight}",
            16: family, 17: weight, 21: family, 22: weight,
        }
        for record in font["name"].names:
            if record.nameID in names:
                record.string = names[record.nameID]
        font.save(destination)


def simplified_charset() -> set[int]:
    codepoints = build_charset()
    for lead in range(0xA1, 0xF8):
        for trail in range(0xA1, 0xFF):
            try:
                codepoints.add(ord(bytes((lead, trail)).decode("gb2312")))
            except UnicodeDecodeError:
                continue
    return codepoints


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("noto_sans_variable", type=Path)
    parser.add_argument("liberation_directory", type=Path)
    parser.add_argument("additional_fonts", type=Path)
    args = parser.parse_args()

    sans_common = []
    sans_full = []
    for style, weight in (("Regular", 400), ("Bold", 700)):
        full = FONT_DIR / f"NotoSansSC-{style}-full-v1.ttf"
        common = FONT_DIR / f"NotoSansSC-{style}-common-v1.ttf"
        with TTFont(args.noto_sans_variable, recalcTimestamp=False) as source:
            font = instantiateVariableFont(source, {"wght": weight}, updateFontNames=True)
            font.save(full)
        subset_font(full, common, build_charset())
        sans_common.append(common)
        sans_full.append(full)

    liberation_fonts = []
    for family in ("LiberationSerif", "LiberationSans"):
        for style in ("Regular", "Bold"):
            filename = f"{family}-{style}.ttf"
            destination = FONT_DIR / filename
            shutil.copyfile(args.liberation_directory / filename, destination)
            liberation_fonts.append(destination)
        sample(FONT_DIR / f"{family}-Regular.ttf", FONT_DIR / f"{family}-sample.woff", "Abc 123")

    carlito = []
    for style in ("Regular", "Bold"):
        filename = f"Carlito-{style}.ttf"
        destination = FONT_DIR / filename
        shutil.copyfile(args.additional_fonts / filename, destination)
        carlito.append(destination)
    sample(carlito[0], FONT_DIR / "Carlito-sample.woff", "Abc 123")

    fang = FONT_DIR / "StarJobFang-Regular-v1.ttf"
    alternate_cjk(args.additional_fonts / "ZhuqueFangsong-Regular.ttf", fang, "StarJob Fang", "Regular", simplified_charset())
    sample(fang, FONT_DIR / "StarJobFang-sample-v1.woff", "求职简历 Abc 123")

    sample(FONT_DIR / "NotoSerifSC-Regular-common-v1.ttf", FONT_DIR / "NotoSerifSC-sample.woff", "求职简历 Abc 123")
    sample(sans_common[0], FONT_DIR / "NotoSansSC-sample.woff", "求职简历 Abc 123")

    serif_common = [FONT_DIR / f"NotoSerifSC-{style}-common-v1.ttf" for style in ("Regular", "Bold")]
    serif_full = [FONT_DIR / f"NotoSerifSC-{style}-full-v1.ttf" for style in ("Regular", "Bold")]
    if coverage(serif_common) != coverage(sans_common):
        raise ValueError("The Noto Sans and Serif common fonts must cover the same characters.")

    lines = ["// Generated by scripts/build_resume_font_choices.py. Do not edit by hand."]
    for name, codepoints in (
        ("NOTO_SERIF_ONLY_RANGES", coverage(serif_full) - coverage(sans_full)),
        ("LIBERATION_RANGES", coverage(liberation_fonts)),
        ("CARLITO_RANGES", coverage(carlito)),
        ("STARJOBFANG_RANGES", coverage([fang])),
    ):
        lines.append(f"export const {name}: ReadonlyArray<readonly [number, number]> = [")
        spans = [f"[0x{start:X}, 0x{end:X}]," for start, end in codepoint_ranges(codepoints)]
        lines.extend("  " + " ".join(spans[i:i + 6]) for i in range(0, len(spans), 6))
        lines.extend(["] as const;", ""])
    output = ROOT / "src" / "generated" / "resumeFontFamilyCoverage.ts"
    output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
